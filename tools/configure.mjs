#!/usr/bin/env node
/**
 * configure.mjs — stamps launcher.config.json into the places that can't read
 * it at runtime. Runs automatically before dev / build / worker:deploy.
 *
 *   launcher.config.json → src/config.js             (browser UI; generated, git-ignored)
 *                        → worker/wrangler.jsonc     (Worker name, domain, bucket, vars; generated, git-ignored)
 *                        → src-tauri/tauri.conf.json (productName, identifier, window title,
 *                                                      updater endpoint — edited in place, pubkey untouched)
 *
 * The Rust side and the Worker code include launcher.config.json directly.
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { ROOT, config as cfg } from "./config.mjs";

const changed = [];
async function writeIfChanged(file, content) {
  let old = null;
  try { old = await fs.readFile(file, "utf8"); } catch {}
  if (old === content) return;
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, content);
  changed.push(path.relative(ROOT, file));
}

// 1. Browser UI
const uiConfig = {
  studio: cfg.studio,
  launcher: { productName: cfg.launcher.productName, installFolder: cfg.launcher.installFolder, codePrefix: cfg.launcher.codePrefix, logo: cfg.launcher.logo || "logo.png" },
  server: { apiUrl: cfg.server.apiUrl },
  links: cfg.links,
  legal: cfg.legal || {},
};
await writeIfChanged(path.join(ROOT, "src", "config.js"),
  `// GENERATED by tools/configure.mjs from launcher.config.json — do not edit.\nwindow.LAUNCHER_CONFIG = ${JSON.stringify(uiConfig, null, 2)};\n`);

// 2. Cloudflare Worker config
const rl = cfg.server.authRateLimit || { limit: 30, period: 10 };
// Download counters (worker/src/stats.mjs) live in a D1 database. Optional: no id → nothing is counted.
const statsBinding = cfg.server.statsDatabaseId
  ? `,

  // Download counts (per version / platform / tier — no personal data). See README "Download stats".
  "d1_databases": [{ "binding": "STATS", "database_name": ${JSON.stringify(cfg.server.statsDatabaseName || `${cfg.server.workerName}-stats`)}, "database_id": ${JSON.stringify(cfg.server.statsDatabaseId)} }]`
  : "";
await writeIfChanged(path.join(ROOT, "worker", "wrangler.jsonc"), `{
  // GENERATED by tools/configure.mjs from launcher.config.json — edit that file, not this one.
  // Deploy:  npm run worker:deploy   (see README "Going to production")
  "name": ${JSON.stringify(cfg.server.workerName)},
  "main": "src/index.mjs",
  "compatibility_date": "2026-05-24",
  "observability": { "enabled": true },

  // Custom domain — Cloudflare creates the DNS record on first deploy
  // (the zone must be in the same Cloudflare account).
  "routes": [{ "pattern": ${JSON.stringify(cfg.server.customDomain)}, "custom_domain": true }],

  // Game files + catalog.json live here. Create once:  npx wrangler r2 bucket create ${cfg.server.bucket}
  "r2_buckets": [{ "binding": "CDN", "bucket_name": ${JSON.stringify(cfg.server.bucket)} }],

  // Built-in Workers rate limiting: per-IP cap on the login routes.
  "ratelimits": [
    { "name": "AUTH_LIMITER", "namespace_id": "1001", "simple": { "limit": ${rl.limit}, "period": ${rl.period} } }
  ],

  "vars": {
    "PUBLIC_URL": ${JSON.stringify(cfg.server.apiUrl)},
    "TOKEN_DAYS": ${JSON.stringify(String(cfg.server.tokenDays ?? 7))}
  }${statsBinding}
  // Secrets (never in any file):  npx wrangler secret put <NAME>
  //   PATREON_CLIENT_ID, PATREON_CLIENT_SECRET,
  //   SUBSCRIBESTAR_CLIENT_ID, SUBSCRIBESTAR_CLIENT_SECRET,
  //   SESSION_SECRET  (any long random string; rotating it signs everyone out)
  //   STATS_PASSWORD  (optional; unlocks /stats — the private download counts page)
}
`);

// 3. tauri.conf.json — edit specific fields in place, keep everything else (incl. the updater pubkey)
const tauriPath = path.join(ROOT, "src-tauri", "tauri.conf.json");
const tauri = JSON.parse(await fs.readFile(tauriPath, "utf8"));
tauri.productName = cfg.launcher.productName;
tauri.identifier = cfg.launcher.identifier;
for (const w of tauri.app?.windows || []) w.title = cfg.launcher.productName;
if (tauri.plugins?.updater) tauri.plugins.updater.endpoints = [`${cfg.server.apiUrl}/launcher/latest.json`];
await writeIfChanged(tauriPath, JSON.stringify(tauri, null, 2) + "\n");

console.log(changed.length ? `configure: updated ${changed.join(", ")}` : "configure: everything already up to date");
